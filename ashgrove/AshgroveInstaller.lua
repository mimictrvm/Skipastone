		local last = os.clock()
		while true do
			task.wait(Config.entities.stepInterval)
			local now = os.clock()
			local dt = now - last
			last = now
			for _, e in Registry.all() do
				if e.status == "active" then
					if not e.model or not e.model.Parent or not e.root then
						-- Lost its body (destroyed by something else): re-form later.
