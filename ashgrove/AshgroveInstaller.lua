	local hitPosition = if result then result.Position else origin + dir * cfg.range
	local kind = if result then "world" else "none"

	local handle = tool:FindFirstChild("Handle") :: BasePart?
	if handle then
		Audio.play("gunshot", handle, 1, 300)
