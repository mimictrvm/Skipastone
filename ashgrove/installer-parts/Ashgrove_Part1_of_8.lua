						if count > bestCount and Banshee.canKeen(wing) then
							bestWing, bestCount = wing, count
						end
					end
					if bestWing and Banshee.keen(bestWing) then
						-- scheduled again when it resolves
						nextNaturalAt = math.huge
					else
						nextNaturalAt = now + 20
					end
				end
			end
		end
